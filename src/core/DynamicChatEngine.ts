function sample(arr: string[]): string {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getKannadaPlanetName(planetName: string): string {
  const map: Record<string, string> = {
    Sun: "ರವಿ",
    Moon: "ಚಂದ್ರ",
    Mars: "ಕುಜ",
    Mercury: "ಬುಧ",
    Jupiter: "ಗುರು",
    Venus: "ಶುಕ್ರ",
    Saturn: "ಶನಿ",
    Rahu: "ರಾಹು",
    Ketu: "ಕೇತು",
  };
  return map[planetName] || planetName;
}

