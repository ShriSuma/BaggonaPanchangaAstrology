export function getNavLabel(key: string, lang: string): string {
  const code = (lang || "kn").slice(0, 2) as SupportedNavLang;
  const langKey = ["kn", "en", "hi", "te", "ta"].includes(code) ? code : "kn";
  const item = T_DRAWER_NAV[key];
  if (!item) return key;
  return item[langKey] || item.kn || item.en || key;
}
