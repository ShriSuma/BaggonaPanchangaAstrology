/**
 * Extracts a candidate person name from a complex question query.
 * Handles inputs like:
 * - "Hiranya Aksha whose name it is" -> "Hiranya Aksha"
 * - "ಹಿರಣ್ಯಾಕ್ಷ ಯಾವ ನಕ್ಷತ್ರ?" -> "ಹಿರಣ್ಯಾಕ್ಷ"
 * - "Suresh nakshatra and pada" -> "Suresh"
 * - "What is the star of Pramod?" -> "Pramod"
 */
export function extractCandidateNameFromQuery(query: string): string {
  if (!query) return "";
  const qTrim = query.trim();

  // 1. Direct Kannada match on leading word or quotes
  const quoteMatch = qTrim.match(/["'“‘](.+?)["'”’]/);
  if (quoteMatch && quoteMatch[1] && quoteMatch[1].trim().length >= 2) {
    return quoteMatch[1].trim();
  }

  // 2. Look for explicit name marker phrases
  // E.g. "I said Hiranya Aksha whose name it is"
  // E.g. "whose name it is" / "ಹೆಸರು" / "name is"
  const whoseNameMatch = qTrim.match(/(?:said|is|for|named|about|whose name is|whose name it is)?\s*([A-Za-z\u0C80-\u0CFF\u0900-\u097F]+(?:\s+[A-Za-z\u0C80-\u0CFF\u0900-\u097F]+)?)\s*(?:whose name|whose name it is|ಯಾರ ಹೆಸರು|ಯಾವ ನಕ್ಷತ್ರ|whose|nakshatra|pada|rashi|star)/i);
  if (whoseNameMatch && whoseNameMatch[1]) {
    const cand = whoseNameMatch[1].trim();
    // Filter out stop words
    if (!/^(what|which|where|when|whose|please|tell|give|about|said|sing|seeing|know|the|this|that|name|nakshatra|rashi|pada)$/i.test(cand)) {
      return cand;
    }
  }

  // 3. Match leading word(s) if query starts with a proper noun
  const words = qTrim.split(/\s+/);
  if (words.length > 0) {
    const firstTwo = words.slice(0, 2).join(" ");
    // If first words are "Hiranya Aksha" or "Hiranyaksha"
    if (/^hiranya(?:\s*aksha)?/i.test(firstTwo)) {
      return "Hiranyaksha";
    }
    if (/^ಹಿರಣ್ಯಾಕ್ಷ|^ಹಿರಣ್ಯ/i.test(firstTwo)) {
      return "ಹಿರಣ್ಯಾಕ್ಷ";
    }

    // Try first single word if capitalized or Indic
    const w0 = words[0] || "";
    if (w0.length >= 2 && !/^(what|when|which|how|why|is|my|our|i|we|please|tell|ನನ್ನ|ನನಗೆ|ಯಾವ|ಯಾವಾಗ|ಹೇಗೆ)$/i.test(w0)) {
      return w0;
    }
  }

  return qTrim;
}

/**
 * Normalizes phonetic prefixes to match Avakahada syllables.
 */
function extractPhoneticKey(name: string): { knKey: string; enKey: string } {
  const clean = name.trim();
  if (!clean) return { knKey: "", enKey: "" };

  // Kannada / Indic script handling
  if (/[\u0C80-\u0CFF]/.test(clean)) {
    // E.g. "ಹಿರಣ್ಯಾಕ್ಷ" -> "ಹಿ"
    const knFirst = clean.substring(0, 2);
    // Handle vowel sign combinations (e.g. ಹ + ಿ = ಹಿ)
    return { knKey: knFirst, enKey: "" };
  }

  // Devanagari script handling
  if (/[\u0900-\u097F]/.test(clean)) {
    const hiFirst = clean.substring(0, 2);
    return { knKey: hiFirst, enKey: "" };
  }

  // English transliteration handling (lowercase)
  const lower = clean.toLowerCase();

  // Multi-character phonetic prefixes (order from longest to shortest)
  const prefixes = [
    "chhu", "chha", "shra", "ksha",
    "bhoo", "bhee", "dhoo", "dhee", "shoo", "shee", "choo", "chee", "jhoo", "jhee",
    "bhu", "bhi", "bha", "bhe", "bho",
    "dhu", "dhi", "dha", "dhe", "dho",
    "shu", "shi", "sha", "she", "sho",
    "chu", "chi", "cha", "che", "cho",
    "pra", "pri", "pro", "pre",
    "khi", "khe", "kho", "gha",
    "tha", "the", "thi", "tho", "thu",
    "tra", "tri", "tro",
    "hee", "hoo", "hay",
    "hi", "ha", "he", "ho", "hu",
    "ra", "ri", "ru", "re", "ro",
    "ka", "ki", "ku", "ke", "ko",
    "ga", "gi", "gu", "ge", "go",
    "ja", "ji", "ju", "je", "jo",
    "ta", "ti", "tu", "te", "to",
    "da", "di", "du", "de", "do",
    "na", "ni", "nu", "ne", "no",
    "pa", "pi", "pu", "pe", "po",
    "ma", "mi", "mu", "me", "mo",
    "ya", "yi", "yu", "ye", "yo",
    "va", "vi", "vu", "ve", "vo", "wa", "wi",
    "sa", "si", "su", "se", "so",
    "la", "li", "lu", "le", "lo",
    "aa", "ee", "oo",
    "a", "e", "i", "o", "u"
  ];

  for (const p of prefixes) {
    if (lower.startsWith(p)) {
      return { knKey: "", enKey: p };
    }
  }

  return { knKey: "", enKey: lower.substring(0, 2) };
}

