export function buildMalayalamDoshaProfiles(ctx: StoryEngineInput): ActiveDoshaProfile[] {
  const out: ActiveDoshaProfile[] = [];
  const rawList = (ctx.activeRawDoshas || []).filter((d) => d?.isDetected);
  const isMinor = ctx.ageYears < 18;
  const severityLabelMl = (sev: string) => {
    const s = String(sev || "").toLowerCase();
    if (s.includes("high") || s.includes("severe")) return "പ്രധാന ശ്രദ്ധ വേണ്ടത്";
    if (s.includes("moderate") || s.includes("medium")) return "മിതമായ സ്വാധീനം";
    return "സൂക്ഷ്മ സ്വാധീനം";
  };

  for (const d of rawList.slice(0, 3)) {
    const title = DOSHA_NAMES_ML[d.id] || "ജാതക ഗ്രഹദോഷം";
    const isKuja = d.id === "kuja_dosha";
    const isSarpa = d.id === "kala_sarpa";
    const isShani = d.id === "gochara_shani";
    out.push({
      id: d.id,
      title,
      severityLabel: severityLabelMl(d.severity),
      doingNow: isMinor
        ? `${ctx.devoteeName}-ന്റെ പ്രായത്തിനനുസരിച്ച് ചെറിയ അശ്രദ്ധയും ഉറക്കത്തിലെ ചഞ്ചലതയും ചിട്ടപ്പെടുത്തേണ്ട ഘട്ടം.`
        : isKuja
        ? `ചൊവ്വയുടെ ബലവും ${ctx.lagnaRashiName} ലഗ്നസ്ഥിതിയും കാരണം പെട്ടെന്നുള്ള ദേഷ്യവും ധൃതിയും ഒഴിവാക്കി സംഭാഷണത്തിൽ സൗമ്യത പാലിക്കണം.`
        : isSarpa
        ? "രാഹു-കേതു അച്ചുതണ്ടിന്റെ സ്വാധീനം കാരണം പ്രയത്നഫലം ലഭിക്കാൻ അല്പം കാത്തിരിപ്പും കൃത്യമായ ആസൂത്രണവും ആവശ്യമായി വരുന്നു."
        : isShani
        ? `ചന്ദ്രനിൽ നിന്ന് ${ctx.shaniHouseFromMoon}-ാം ഭാവത്തിലെ ശനി സഞ്ചാരം ഉത്തരവാദിത്തബോധവും ക്ഷമയും വളർത്തുന്നു.`
        : `${ctx.currentMahadasha} ദശയിൽ അനാവശ്യ ചിന്താഭാരം ഒഴിവാക്കി വ്യക്തമായ ദിനചര്യയിലൂടെ മനഃശാന്തി നിലനിർത്തേണ്ട സമയം.`,
      affectingArea: isMinor ? "പഠന ശ്രദ്ധയും ശാരീരിക ഉന്മേഷവും" : "കുടുംബ സമാധാനവും തൊഴിൽ-സാമ്പത്തിക സ്ഥിരതയും",
      exactAction: `${ctx.localizedYogiDay} ദിവസങ്ങളിൽ ശുദ്ധമനസ്സോടെ ശ്രീ ഗോകർണ്ണ മഹാബലേശ്വര സ്മരണയും ദീപാരാധനയും നടത്തുക.`
    });
  }

  const maandiSav = ctx.savTable[(ctx.lagnaRashiIdx + ctx.maandiHouse - 1) % 12] ?? 28;
  out.push({
    id: "maandi_knot_audit",
    title: `മാന്ദി സ്ഥാന പരിശോധന (${ctx.maandiHouse}-ാം ഭാവം • ${ctx.maandiRashiName})`,
    severityLabel: "സൂക്ഷ്മ വിന്യാസം",
    doingNow: isMinor
      ? `${ctx.maandiDomainAffected} മേഖലയിൽ കുട്ടിക്ക് ചെറിയ കൗതുകവും മൃദുല സ്വഭാവവും പ്രകടമാകുന്നു (${maandiSav} ബിന്ദു).`
      : `${ctx.maandiDomainAffected} മേഖലയിൽ മറ്റുള്ളവരോട് തുറന്നു പറയാത്ത സൂക്ഷ്മമായ ആശങ്കകൾ മനസ്സിൽ തങ്ങുന്നു (${maandiSav} ബിന്ദു).`,
    affectingArea: ctx.maandiDomainAffected,
    exactAction: `നിത്യേന രാവിലെ 10 മിനിറ്റ് ശാന്തമായി വിളക്കു തെളിയിച്ച് ${ctx.yogiPlanetName} സ്മരണയും സത്കർമ്മവും ചെയ്യുക.`
  });

  return out;
}

